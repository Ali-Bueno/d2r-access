#!/usr/bin/env python3
r"""gen_skill_tree.py -- Generates src/generated/skill_tree.h: where each skill
of each class stands in its skill tree.

Why this exists
---------------
In keyboard mode the skill tree has no button for a skill: the panel draws the
skills itself, from the page, row and column skilldesc.txt gives each one. The
keyboard's cursor has to reach every one of them with the arrows alone (the
user, 2026-09-27: "be absolutely sure no items or skills are skipped"), and
the trees have gaps: the Paladin's first page has a skill in row 1, column 1,
none in row 1, column 2, and the next in row 2, column 2. The cursor's tests
walk every page of every class from this table.

The rules. Each is a column of the game's tables, not a list of names:

  skills.txt     charclass      the class the skill is of; empty for the rest
                 skilldesc      the row of skilldesc.txt that describes it
                 *Id            the skill id
  skilldesc.txt  SkillPage      1 to 3; 0 is a skill that is on no page
                 SkillRow       1 to 6, from the top
                 SkillColumn    1 to 3, from the left
  PlayerClass.txt               the classes in the order of their ids; the
                                line with no code divides the expansion's

Usage:
    python tools/gen_skill_tree.py [--excel game-data/global/excel]
                                   [--out src/generated/skill_tree.h]

The tables come from the game's CASC storage:
    tools/casc_extract.exe extract "<game dir>" game-data "excel\skilldesc.txt"
and land in game-data/global/excel/. game-data/ is gitignored; the generated
header is what gets committed.
"""
import argparse
import csv
import io
from pathlib import Path

PAGES, ROWS, COLUMNS = 3, 6, 3


def table(path):
    with io.open(path, encoding="utf-8-sig", errors="replace", newline="") as source:
        return list(csv.DictReader(source, delimiter="\t"))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--excel", type=Path, default=Path("game-data/global/excel"))
    parser.add_argument("--out", type=Path, default=Path("src/generated/skill_tree.h"))
    args = parser.parse_args()

    classes = [row["Code"].strip() for row in table(args.excel / "PlayerClass.txt") if (row.get("Code") or "").strip()]
    described = {row["skilldesc"].strip(): row for row in table(args.excel / "skilldesc.txt")}

    skills = []
    taken = {}
    for row in table(args.excel / "skills.txt"):
        code = (row.get("charclass") or "").strip()
        about = described.get((row.get("skilldesc") or "").strip())
        number = (row.get("*Id") or "").strip()
        if not code or about is None or not number.isdigit():
            continue
        try:
            page, line, column = int(about["SkillPage"]), int(about["SkillRow"]), int(about["SkillColumn"])
        except ValueError:
            continue
        if page < 1:
            continue
        if code not in classes:
            raise SystemExit("skills.txt: %s is of class %r, which PlayerClass.txt does not have" % (row["skill"], code))
        if not (page <= PAGES and 1 <= line <= ROWS and 1 <= column <= COLUMNS):
            raise SystemExit("skilldesc.txt: %s stands at page %d, row %d, column %d" % (row["skill"], page, line, column))
        place = (classes.index(code), page, line, column)
        if place in taken:
            raise SystemExit("skilldesc.txt: %s and %s stand in the same place" % (row["skill"], taken[place]))
        taken[place] = row["skill"]
        skills.append(place + (int(number), row["skill"]))
    skills.sort()
    if not skills:
        raise SystemExit("no skill of any class found")

    out = []
    out.append("// generated by tools/gen_skill_tree.py from game-data -- do not edit")
    out.append("//")
    out.append("// Where each skill of each class stands in its skill tree, from skills.txt")
    out.append("// and skilldesc.txt: %d skills of %d classes. The page is 1 to %d, the row 1 to"
               % (len(skills), len(classes), PAGES))
    out.append("// %d from the top, the column 1 to %d from the left, as the tables count them." % (ROWS, COLUMNS))
    out.append("#pragma once")
    out.append("")
    out.append("#include <array>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace D2RAccess::Generated {")
    out.append("")
    out.append("inline constexpr int SkillTreeClasses = %d, SkillTreePages = %d, SkillTreeRows = %d, SkillTreeColumns = %d;"
               % (len(classes), PAGES, ROWS, COLUMNS))
    out.append("")
    out.append("struct TreeSkill {")
    out.append("\tuint8_t playerClass, page, row, column;")
    out.append("\tuint16_t skill;")
    out.append("};")
    out.append("")
    out.append("// Sorted by class, page, row and column.")
    out.append("inline constexpr std::array<TreeSkill, %d> SkillTree{{" % len(skills))
    last = None
    for player, page, line, column, skill, name in skills:
        if (player, page) != last:
            out.append("\t// %s, page %d" % (classes[player], page))
            last = (player, page)
        out.append("\t{%d, %d, %d, %d, %d}, // %s" % (player, page, line, column, skill, name))
    out.append("}};")
    out.append("")
    out.append("}")
    out.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    io.open(args.out, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("%s: %d skills of %d classes" % (args.out, len(skills), len(classes)))


if __name__ == "__main__":
    main()
