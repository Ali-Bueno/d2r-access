#!/usr/bin/env python3
r"""gen_item_sizes.py -- Generates src/generated/item_sizes.h, the cells each
item takes up in an inventory grid, keyed by the item code the plugin already
reads from a unit's items table row.

Why this exists
---------------
An item covers a block of cells -- a short sword one column by three rows, a
body armour two by three -- and the game refuses to take an item when no free
block of that shape exists, however many single cells are free. A player who
cannot see the grid needs to hear the shape (the user, 2026-09-21: "that is
important information to have").

The size is invwidth x invheight in weapons.txt, armor.txt and misc.txt. The
runtime items table row holds it too, but its layout differs from classic D2
exactly in that region (the name moved +8, the type +0x10), so reading it by
offset would be a guess. The row's item code (+0x80) is already read and
verified by the ground item reader, so the size is looked up by code instead.

Usage:
    python tools/gen_item_sizes.py [--excel game-data/global/excel]
                                   [--out src/generated/item_sizes.h]

The three tables come from the game's CASC storage:
    tools/casc_extract.exe extract "<game dir>" game-data "excel\weapons.txt"
    (and the same for armor.txt and misc.txt)
and land in game-data/global/excel/. game-data/ is gitignored; the generated
header is what gets committed.
"""
import argparse
import csv
import io
from pathlib import Path

TABLES = ("weapons.txt", "armor.txt", "misc.txt")


def packed(code):
    """The item code as the game stores it: little-endian, space-padded."""
    text = code.ljust(4)
    return sum(ord(ch) << (8 * i) for i, ch in enumerate(text))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--excel", type=Path, default=Path("game-data/global/excel"))
    parser.add_argument("--out", type=Path, default=Path("src/generated/item_sizes.h"))
    args = parser.parse_args()

    sizes = {}
    for table in TABLES:
        with io.open(args.excel / table, encoding="utf-8-sig", errors="replace", newline="") as source:
            rows = list(csv.reader(source, delimiter="\t"))
        header = rows[0]
        code_at, width_at, height_at = header.index("code"), header.index("invwidth"), header.index("invheight")
        for row in rows[1:]:
            if len(row) <= max(code_at, width_at, height_at):
                continue
            code, width, height = row[code_at].strip(), row[width_at].strip(), row[height_at].strip()
            # The "Expansion" separator rows carry no code and no size.
            if not code or not width.isdigit() or not height.isdigit():
                continue
            if not 1 <= len(code) <= 4 or not code.isascii():
                raise SystemExit("%s: unusable item code %r" % (table, code))
            if code in sizes:
                raise SystemExit("%s: item code %r already defined in %s" % (table, code, sizes[code][2]))
            sizes[code] = (int(width), int(height), table)

    entries = sorted(sizes.items(), key=lambda item: packed(item[0]))
    widest = max(width for width, _, _ in sizes.values())
    tallest = max(height for _, height, _ in sizes.values())

    out = []
    out.append("// generated by tools/gen_item_sizes.py from game-data -- do not edit")
    out.append("//")
    out.append("// The cells each item takes up in an inventory grid, invwidth x invheight")
    out.append("// from weapons.txt, armor.txt and misc.txt, by the item code the plugin")
    out.append("// reads from a unit's items table row. %d items; the largest is %d wide"
               % (len(entries), widest))
    out.append("// and %d tall." % tallest)
    out.append("#pragma once")
    out.append("")
    out.append("#include <algorithm>")
    out.append("#include <array>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace D2RAccess::Generated {")
    out.append("")
    out.append("struct ItemSize { uint32_t code; uint8_t width, height; };")
    out.append("")
    out.append("// An item code as the game stores it: little-endian, space-padded.")
    out.append("constexpr uint32_t ItemCode(const char (&text)[4]) {")
    out.append("\treturn static_cast<uint32_t>(static_cast<unsigned char>(text[0]))")
    out.append("\t\t| static_cast<uint32_t>(static_cast<unsigned char>(text[1])) << 8")
    out.append("\t\t| static_cast<uint32_t>(static_cast<unsigned char>(text[2])) << 16 | 0x20000000u;")
    out.append("}")
    out.append("")
    out.append("// Sorted by code, so a lookup is a binary search over %d items." % len(entries))
    out.append("inline constexpr std::array<ItemSize, %d> ItemSizes{{" % len(entries))
    row_text = "\t"
    for code, (width, height, _) in entries:
        if len(code) != 3:
            raise SystemExit("item code %r is not three letters; extend ItemCode" % code)
        piece = '{ItemCode("%s"), %d, %d},' % (code, width, height)
        if len(row_text) + len(piece) > 78:
            out.append(row_text.rstrip())
            row_text = "\t"
        row_text += piece + " "
    if row_text.strip():
        out.append(row_text.rstrip())
    out.append("}};")
    out.append("static_assert(std::is_sorted(ItemSizes.begin(), ItemSizes.end(),")
    out.append("\t[](const ItemSize& a, const ItemSize& b) { return a.code < b.code; }));")
    out.append("")
    out.append("// The cells an item takes up, by the code in its items table row. A NUL")
    out.append("// byte is taken as the space the game pads a short code with. Width and")
    out.append("// height are 0 for a code the tables do not know.")
    out.append("constexpr ItemSize ItemSizeFor(uint32_t code) {")
    out.append("\tfor (int shift = 0; shift < 32; shift += 8)")
    out.append("\t\tif (((code >> shift) & 0xFFu) == 0) code |= 0x20u << shift;")
    out.append("\tconst auto it = std::lower_bound(ItemSizes.begin(), ItemSizes.end(), code,")
    out.append("\t\t[](const ItemSize& entry, uint32_t wanted) { return entry.code < wanted; });")
    out.append("\treturn it != ItemSizes.end() && it->code == code ? *it : ItemSize{code, 0, 0};")
    out.append("}")
    out.append("")
    out.append("}")
    out.append("")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    io.open(args.out, "w", encoding="utf-8", newline="\n").write("\n".join(out))
    print("%s: %d item sizes, largest %d x %d" % (args.out, len(entries), widest, tallest))


if __name__ == "__main__":
    main()
