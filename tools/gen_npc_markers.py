#!/usr/bin/env python3
r"""gen_npc_markers.py -- Generates src/generated/npc_markers.h: the invisible marker
objects some NPCs are spawned at (Jerhyn, Hratli, Natalya, Anya, Nihlathak, Larzuk).

These NPCs are no monster preset of their town: the town's DS1 places a marker object
whose objects.txt InitFn spawns the NPC when the marker's room is built, if the
function's own test passes (docs/entity-scan.md#town-npcs). The rule is a pair of
columns, not a list of names:

  objects.txt Class starts with the Id of a MonStats row whose npc column is 1
  (JerhynPlaceholder1 -> jerhyn, NatalyaStart -> natalya); the longest Id wins.

Usage:
    python tools/gen_npc_markers.py [--excel game-data/global/excel]
                                    [--out src/generated/npc_markers.h]
"""
import argparse
import csv
import io
from pathlib import Path


def table(path):
    with io.open(path, encoding="utf-8-sig", errors="replace", newline="") as source:
        rows = list(csv.reader(source, delimiter="\t"))
    header = rows[0]
    return [{name: (row[i].strip() if i < len(row) else "") for i, name in enumerate(header)} for row in rows[1:]]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--excel", type=Path, default=Path("game-data/global/excel"))
    parser.add_argument("--out", type=Path, default=Path("src/generated/npc_markers.h"))
    args = parser.parse_args()

    npcs = {row["Id"].lower(): (int(row["*hcIdx"]), row["Id"]) for row in table(args.excel / "monstats.txt")
            if row["npc"] == "1" and row["*hcIdx"].isdigit()}
    entries = []
    for row in table(args.excel / "objects.txt"):
        if not row["*ID"].isdigit() or not row["InitFn"].isdigit() or row["InitFn"] == "0":
            continue
        name = row["Class"].lower()
        matches = [npc for npc in npcs if name.startswith(npc)]
        if matches:
            monster, npc = npcs[max(matches, key=len)]
            entries.append((int(row["*ID"]), monster, int(row["InitFn"]), row["Class"], npc))

    out = []
    out.append("// generated by tools/gen_npc_markers.py from game-data -- do not edit")
    out.append("//")
    out.append("// Marker objects an NPC is spawned at by the marker's objects.txt InitFn, when")
    out.append("// the marker's room is built. %d markers." % len(entries))
    out.append("#pragma once")
    out.append("")
    out.append("#include <array>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace D2RAccess::Generated {")
    out.append("")
    out.append("struct NpcMarker {")
    out.append("\tuint32_t object;  // objects.txt row of the marker")
    out.append("\tuint32_t monster; // MonStats row of the NPC")
    out.append("\tint initFn;       // objects.txt InitFn: the game's code that spawns it")
    out.append("};")
    out.append("")
    out.append("inline constexpr std::array<NpcMarker, %d> NpcMarkers{{" % len(entries))
    for obj, monster, init, cls, npc in entries:
        out.append("\t{%d, %d, %d}, // %s -> %s" % (obj, monster, init, cls, npc))
    out.append("}};")
    out.append("")
    out.append("}")
    args.out.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print("%s: %d markers" % (args.out, len(entries)))


if __name__ == "__main__":
    main()
