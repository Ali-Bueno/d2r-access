// Build step: seals every .txt and .tsv under a folder (data/descriptions/<locale>.txt,
// data/audiodesc/<edition>/<locale>.txt, data/audiodesc/speech.tsv) into one blob the plugin
// embeds, each named by its path without the extension ("enUS", "hd/enUS", "speech"), and writes
// the key it opens with. docs/descriptions.md
//   seal-descriptions <folder> <sealed output> <key header output> [<key name>]

#include "sealed_text.h"

#include <algorithm>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <sstream>

using namespace D2RAccess;

namespace {
std::string ReadFile(const std::filesystem::path& path) {
	std::ifstream input(path, std::ios::binary);
	std::stringstream text;
	text << input.rdbuf();
	std::string content = text.str();
	if (content.starts_with("\xEF\xBB\xBF")) content.erase(0, 3); // Notepad's byte-order mark
	return content;
}

int Fail(const char* message) {
	std::fprintf(stderr, "seal-descriptions: %s\n", message);
	return 1;
}
}

int main(int argc, char** argv) {
	if (argc != 4 && argc != 5) return Fail("usage: seal-descriptions <folder> <sealed output> <key header output> [<key name>]");
	const std::string keyName = argc == 5 ? argv[4] : "DescriptionsKey";
	const std::filesystem::path folder = argv[1];
	SealedText::Texts texts;
	for (const auto& entry : std::filesystem::recursive_directory_iterator(folder))
		if (entry.is_regular_file() && (entry.path().extension() == ".txt" || entry.path().extension() == ".tsv"))
			texts[entry.path().lexically_relative(folder).replace_extension().generic_string()] = ReadFile(entry.path());
	if (!std::ranges::any_of(texts, [](const auto& text) { return text.first == "enUS" || text.first.ends_with("/enUS"); }))
		return Fail("no enUS.txt; every language falls back to it");

	const auto key = SealedText::NewKey();
	const auto sealed = key ? SealedText::Seal(SealedText::Pack(texts), *key) : std::nullopt;
	if (!sealed) return Fail("the system refused to seal");
	std::ofstream(argv[2], std::ios::binary).write(reinterpret_cast<const char*>(sealed->data()),
		static_cast<std::streamsize>(sealed->size()));

	std::ofstream header(argv[3], std::ios::binary);
	header << "// Generated by seal-descriptions at build time: the key the texts are sealed under.\n"
		"#pragma once\n#include \"sealed_text.h\"\n"
		"namespace D2RAccess::Generated {\ninline constexpr SealedText::Key " << keyName << "{";
	for (size_t i = 0; i < key->size(); ++i) {
		char byte[8];
		std::snprintf(byte, sizeof byte, "%s0x%02X", i ? ", " : "", (*key)[i]);
		header << byte;
	}
	header << "};\n}\n";
	std::printf("seal-descriptions: %zu files sealed, %zu bytes\n", texts.size(), sealed->size());
	return 0;
}
