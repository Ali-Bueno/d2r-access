// Build step: seals every data/descriptions/<locale>.txt into one blob the plugin embeds, and writes
// the key it opens with. docs/descriptions.md
//   seal-descriptions <descriptions folder> <sealed output> <key header output>
#include "sealed_text.h"

#include <cstdio>
#include <filesystem>
#include <fstream>
#include <sstream>

using namespace D2RAccess;

namespace {
std::string ReadFile(const std::filesystem::path& path) {
	std::ifstream input(path, std::ios::binary);
	std::stringstream text;
	text << input.rdbuf();
	std::string content = text.str();
	if (content.starts_with("\xEF\xBB\xBF")) content.erase(0, 3); // Notepad's byte-order mark
	return content;
}

int Fail(const char* message) {
	std::fprintf(stderr, "seal-descriptions: %s\n", message);
	return 1;
}
}

int main(int argc, char** argv) {
	if (argc != 4) return Fail("usage: seal-descriptions <folder> <sealed output> <key header output>");
	SealedText::Texts texts;
	for (const auto& entry : std::filesystem::directory_iterator(argv[1]))
		if (entry.is_regular_file() && entry.path().extension() == ".txt")
			texts[entry.path().stem().string()] = ReadFile(entry.path());
	if (!texts.contains("enUS")) return Fail("enUS.txt is missing; every language falls back to it");

	const auto key = SealedText::NewKey();
	const auto sealed = key ? SealedText::Seal(SealedText::Pack(texts), *key) : std::nullopt;
	if (!sealed) return Fail("the system refused to seal");
	std::ofstream(argv[2], std::ios::binary).write(reinterpret_cast<const char*>(sealed->data()),
		static_cast<std::streamsize>(sealed->size()));

	std::ofstream header(argv[3], std::ios::binary);
	header << "// Generated by seal-descriptions at build time: the key the descriptions are sealed under.\n"
		"#pragma once\n#include \"sealed_text.h\"\n"
		"namespace D2RAccess::Generated {\ninline constexpr SealedText::Key DescriptionsKey{";
	for (size_t i = 0; i < key->size(); ++i) {
		char byte[8];
		std::snprintf(byte, sizeof byte, "%s0x%02X", i ? ", " : "", (*key)[i]);
		header << byte;
	}
	header << "};\n}\n";
	std::printf("seal-descriptions: %zu languages sealed, %zu bytes\n", texts.size(), sealed->size());
	return 0;
}
