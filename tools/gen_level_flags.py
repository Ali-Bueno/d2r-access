#!/usr/bin/env python3
"""gen_level_flags.py -- Generates src/generated/level_flags.h, a per-level-id
table of two Levels.txt facts the plugin needs to describe a level without
reading game memory: DrlgType (the layout generator: maze/preset/outdoor) and
*IsInside (whether the level has a ceiling/is indoors), read straight off the
row so the plugin never has to guess.

Levels.txt has one non-level row, "Expansion" (all columns blank, including
Id) -- a section separator Blizzard leaves in the sheet, not a real level; it
is skipped like the nameless placeholder rows in tools/objects_containers.py.
The column name is "*IsInside" (the leading "*" is D2's own txt convention for
an engine-ignored/comment column, still present as real data) -- looked up by
that exact header text, never assumed to be at a fixed index.

Stdlib only. Usage (run from the repo root):
    python tools\\gen_level_flags.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REQUIRED_COLUMNS = ("Id", "Name", "DrlgType", "LevelType", "*IsInside")


def load_rows(levels_txt: Path) -> list[dict[str, str]]:
    lines = levels_txt.read_text(encoding="utf-8-sig").splitlines()
    header = lines[0].split("\t")
    missing = [c for c in REQUIRED_COLUMNS if c not in header]
    if missing:
        raise SystemExit(f"{levels_txt}: missing expected column(s) {missing} in header {header}")
    rows = []
    for line in lines[1:]:
        if not line.strip():
            continue
        cols = line.split("\t")
        row = dict(zip(header, cols))
        if row.get("Id", "").strip() == "":
            continue  # the blank "Expansion" separator row, not a level
        rows.append(row)
    return rows


def escape_c_string(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def main() -> int:
    script_path = Path(__file__).resolve()
    default_repo_root = script_path.parent.parent

    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--repo-root", type=Path, default=default_repo_root)
    ap.add_argument("--levels-txt", type=Path, default=None)
    ap.add_argument("--out-header", type=Path, default=None)
    args = ap.parse_args()

    repo_root: Path = args.repo_root
    levels_txt: Path = args.levels_txt or (repo_root / "game-data" / "global" / "excel" / "Levels.txt")
    out_header: Path = args.out_header or (repo_root / "src" / "generated" / "level_flags.h")

    if not levels_txt.is_file():
        print(f"ERROR: Levels.txt not found: {levels_txt}", file=sys.stderr)
        return 1

    rows = load_rows(levels_txt)
    towns = {}
    for row in rows:
        level = int(row["Id"])
        act = int(row["Act"])
        if level > 0: towns[act] = min(level, towns.get(act, level))
    entries = []
    for row in rows:
        entries.append({
            "id": int(row["Id"]),
            "name": row.get("Name", "").strip(),
            "drlgType": int(row["DrlgType"]),
            "inside": row["*IsInside"].strip() == "1",
            "town": int(row["Id"]) == towns.get(int(row["Act"])),
            "levelType": int(row["LevelType"]),
        })
    entries.sort(key=lambda e: e["id"])

    out_header.parent.mkdir(parents=True, exist_ok=True)

    lines: list[str] = []
    lines.append("// generated by tools/gen_level_flags.py from game-data -- do not edit")
    lines.append("//")
    lines.append("// Per-level-id DrlgType and *IsInside, read straight off game-data/global/excel/")
    lines.append("// Levels.txt (unmodified, no interpreted meaning) so the plugin never has to")
    lines.append("// infer indoor/outdoor from anything else. *IsInside is the authoritative flag;")
    lines.append("// drlgType is carried through for callers that need the layout generator kind.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstddef>")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("namespace D2RAccess::Generated {")
    lines.append("")
    lines.append("struct LevelFlags {")
    lines.append("\tint32_t id;")
    lines.append("\tint32_t drlgType; // Levels.txt DrlgType, unmodified")
    lines.append("\tbool inside;      // Levels.txt *IsInside")
    lines.append("\tbool town;        // the lowest non-zero Id of its Levels.txt Act")
    lines.append("\tint32_t levelType; // Levels.txt LevelType: the LvlTypes.txt row, its tile set")
    lines.append("};")
    lines.append("")
    lines.append("inline constexpr LevelFlags LevelFlagsTable[] = {")
    for e in entries:
        name_comment = f" // {escape_c_string(e['name'])}" if e["name"] else ""
        lines.append(
            f"\t{{ {e['id']}, {e['drlgType']}, {'true' if e['inside'] else 'false'}, {'true' if e['town'] else 'false'}, {e['levelType']} }},{name_comment}"
        )
    lines.append("};")
    lines.append("")
    lines.append("// Levels.txt row count (excluding the blank \"Expansion\" separator row): the")
    lines.append("// tripwire a future patch's changed level count should trip -- rerun")
    lines.append("// tools/gen_level_flags.py and diff this value before trusting the table.")
    lines.append(f"inline constexpr size_t LevelRowCount = {len(entries)};")
    lines.append("")
    lines.append("// No level with this id exists in Levels.txt: {} for drlgType/inside is not a")
    lines.append("// valid Levels.txt value, so it can't be mistaken for a real row.")
    lines.append("inline constexpr LevelFlags UnknownLevel{ -1, -1, false, false, -1 };")
    lines.append("")
    lines.append("inline constexpr const LevelFlags& FindLevelFlags(int32_t id) {")
    lines.append("\tfor (const auto& entry : LevelFlagsTable) {")
    lines.append("\t\tif (entry.id == id) return entry;")
    lines.append("\t}")
    lines.append("\treturn UnknownLevel;")
    lines.append("}")
    lines.append("")
    lines.append("}")
    lines.append("")

    out_header.write_text("\r\n".join(lines), encoding="utf-8", newline="")

    inside_count = sum(1 for e in entries if e["inside"])
    from collections import Counter
    drlg_counts = Counter(e["drlgType"] for e in entries)

    print(f"[gen-level-flags] {len(entries)} levels read from {levels_txt.relative_to(repo_root)}")
    print(f"[gen-level-flags] inside: {inside_count}, outside: {len(entries) - inside_count}")
    print(f"[gen-level-flags] DrlgType counts: {dict(sorted(drlg_counts.items()))}")
    print(f"[gen-level-flags] wrote {out_header}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
