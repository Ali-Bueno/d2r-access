#!/usr/bin/env python3
r"""gen_drop_sounds.py -- Generates src/generated/drop_sounds.h and
cmake/DropSounds.cmake: the sound each item makes when it lands on the ground,
so the item loops can play the game's own drop sounds instead of the Diablo IV
set (a tester's suggestion, 2026-10-13; docs/ground-items.md).

The drop sound is the dropsound column of weapons.txt, armor.txt and misc.txt,
a sounds.txt row whose Redirect names the HD row the game plays in HD mode
(item_sword -> item_sword_hd -> item\item_sword_hd.flac). Items are looked up by
the code the plugin already reads from a unit's items table row.

Usage:
    python tools/gen_drop_sounds.py [--excel game-data/global/excel]
        [--casc <extraction dir> --ffmpeg <ffmpeg.exe>]

--casc converts each HD file into sounds/item loop sounds/d2 drops/<name>.ogg;
extract them first with
    build/casc-extract/casc_extract.exe extract "<game dir>" <dir> ".flac"
The excel tables come from the same storage into game-data/global/excel/.
"""
import argparse
import collections
import csv
import io
import subprocess
from pathlib import Path

TABLES = ("weapons.txt", "armor.txt", "misc.txt")
SOUND_DIR = Path("sounds/item loop sounds/d2 drops")


def rows(path):
    with io.open(path, encoding="utf-8-sig", errors="replace", newline="") as source:
        table = list(csv.reader(source, delimiter="\t"))
    header = table[0]
    for row in table[1:]:
        yield dict(zip(header, row + [""] * (len(header) - len(row))))


def packed(code):
    """The item code as the game stores it: little-endian, space-padded."""
    return sum(ord(ch) << (8 * i) for i, ch in enumerate(code.ljust(4)))


def stem(key):
    """item_largemetalweapon -> largemetalweapon; item_worldstone_shard_hd -> worldstone_shard."""
    name = key[len("item_"):] if key.startswith("item_") else key
    return name[:-len("_hd")] if name.endswith("_hd") else name


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--excel", type=Path, default=Path("game-data/global/excel"))
    parser.add_argument("--header", type=Path, default=Path("src/generated/drop_sounds.h"))
    parser.add_argument("--cmake", type=Path, default=Path("cmake/DropSounds.cmake"))
    parser.add_argument("--casc", type=Path)
    parser.add_argument("--ffmpeg", type=Path, default=Path("ffmpeg"))
    args = parser.parse_args()

    sounds = {row["Sound"]: row for row in rows(args.excel / "sounds.txt")}
    drops = {}
    types = {}
    for table in TABLES:
        for row in rows(args.excel / table):
            code, key = row["code"].strip(), row["dropsound"].strip()
            types[code] = row["type"].strip()
            if not code:
                continue  # the "Expansion" separator rows
            if len(code) != 3 or not code.isascii():
                raise SystemExit("%s: item code %r is not three letters; extend ItemCode" % (table, code))
            if key not in sounds:
                raise SystemExit("%s: %s drops with unknown sound %r" % (table, code, key))
            drops[code] = key

    files = {}
    for key in sorted(set(drops.values())):
        redirect = sounds[key]["Redirect"].strip()
        source = (sounds[redirect] if redirect else sounds[key])["FileName"].strip().replace("\\", "/")
        files[key] = (stem(key), source)
    names = sorted({name for name, _ in files.values()})
    if len(names) != len(files):
        raise SystemExit("two drop sounds share a file name")
    index = {key: names.index(name) for key, (name, _) in files.items()}

    # The glossary names each sound after one item that makes it, in the game's own words:
    # the first item of the commonest type among them, a quest type only when nothing else is.
    examples = {}
    for key, (name, _) in files.items():
        codes = [code for code, drop in drops.items() if drop == key]
        counts = collections.Counter(types[code] for code in codes)
        common = max(counts, key=lambda kind: (kind != "ques", counts[kind], -codes.index(next(c for c in codes if types[c] == kind))))
        examples[name] = next(code for code in codes if types[code] == common)

    if args.casc:
        SOUND_DIR.mkdir(parents=True, exist_ok=True)
        for key, (name, source) in sorted(files.items()):
            path = next((p for p in (args.casc / "hd/global/sfx" / source, args.casc / "global/sfx" / source) if p.exists()), None)
            if not path:
                raise SystemExit("%s: %s not in the extraction" % (key, source))
            subprocess.run([str(args.ffmpeg), "-nostdin", "-v", "error", "-y", "-i", str(path), "-map_metadata", "-1",
                            "-ac", "1", "-ar", "48000", "-c:a", "libvorbis", "-q:a", "6", str(SOUND_DIR / (name + ".ogg"))], check=True)

    entries = sorted(drops.items(), key=lambda item: packed(item[0]))
    out = []
    out.append("// generated by tools/gen_drop_sounds.py from game-data -- do not edit")
    out.append("//")
    out.append("// The sound each item makes when it lands, the dropsound of weapons.txt,")
    out.append("// armor.txt and misc.txt in its HD form (sounds.txt Redirect). %d items," % len(entries))
    out.append("// %d sounds, each one file under sounds/item loop sounds/d2 drops/." % len(names))
    out.append("#pragma once")
    out.append("")
    out.append('#include "item_sizes.h"')
    out.append("")
    out.append("#include <algorithm>")
    out.append("#include <array>")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace D2RAccess::Generated {")
    out.append("")
    out.append("inline constexpr std::array<const char*, %d> DropSoundFiles{" % len(names))
    for name in names:
        out.append('\t"%s.wav",' % name)
    out.append("};")
    out.append("")
    out.append("// One item that makes each sound, whose name the sound glossary says.")
    out.append("inline constexpr std::array<uint32_t, %d> DropSoundExamples{" % len(names))
    for name in names:
        out.append('\tItemCode("%s"), // %s' % (examples[name], name))
    out.append("};")
    out.append("")
    out.append("struct DropSound { uint32_t code; uint8_t sound; };")
    out.append("")
    out.append("// Sorted by code, so a lookup is a binary search over %d items." % len(entries))
    out.append("inline constexpr std::array<DropSound, %d> DropSounds{{" % len(entries))
    row_text = "\t"
    for code, key in entries:
        piece = '{ItemCode("%s"), %d},' % (code, index[key])
        if len(row_text) + len(piece) > 78:
            out.append(row_text.rstrip())
            row_text = "\t"
        row_text += piece + " "
    if row_text.strip():
        out.append(row_text.rstrip())
    out.append("}};")
    out.append("static_assert(std::is_sorted(DropSounds.begin(), DropSounds.end(),")
    out.append("\t[](const DropSound& a, const DropSound& b) { return a.code < b.code; }));")
    out.append("")
    out.append("// The DropSoundFiles index of an item's drop sound by its code, -1 for a code")
    out.append("// the tables do not know. A NUL byte is taken as the padding space.")
    out.append("constexpr int DropSoundFor(uint32_t code) {")
    out.append("\tfor (int shift = 0; shift < 32; shift += 8)")
    out.append("\t\tif (((code >> shift) & 0xFFu) == 0) code |= 0x20u << shift;")
    out.append("\tconst auto at = std::lower_bound(DropSounds.begin(), DropSounds.end(), code,")
    out.append("\t\t[](const DropSound& entry, uint32_t value) { return entry.code < value; });")
    out.append("\treturn at != DropSounds.end() && at->code == code ? at->sound : -1;")
    out.append("}")
    out.append("")
    out.append("}")
    args.header.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")

    cmake = ["# generated by tools/gen_drop_sounds.py from game-data -- do not edit",
             "# The game's drop sounds, one per file under sounds/item loop sounds/d2 drops/.",
             "set(D2R_DROP_SOUNDS"]
    cmake += ['\t"%s"' % name for name in names]
    cmake.append(")")
    args.cmake.write_text("\n".join(cmake) + "\n", encoding="utf-8", newline="\n")
    print("%d items, %d sounds" % (len(entries), len(names)))


if __name__ == "__main__":
    main()
