"""Generate src/generated/quest_catalog.h from the extracted game data.

Two facts come straight out of the game's own files, so nothing here is guessed:

* every quest button in the quest log carries its icon filename, and that
  filename encodes the act and the quest number -- Quest0 is "QuestIcons\\a1q1",
  Quest5 is "QuestIcons\\a1q6" (game-data/index/QuestLogPanel*.index.json);
* the quest title and its step-by-step objectives live in the game's string
  table under "qstsa<act>q<quest>" and "qstsa<act>q<quest><step>"
  (game-data/local/lng/strings/quests.json).

Act 5 quest 1 is the one irregular case: its title is "qstsa5q1" but Blizzard
spelled its step keys "qsta5q1<step>" (no second 's'). Both prefixes are
collected so the table stays faithful to the shipped data.

Run manually after a CASC re-extract, like the other generators in this folder;
the emitted header is committed.
"""

from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INDEX_DIR = ROOT / "game-data" / "index"
STRINGS = ROOT / "game-data" / "local" / "lng" / "strings" / "quests.json"
OUTPUT = ROOT / "src" / "generated" / "quest_catalog.h"

PANELS = ("QuestLogPanelExpansionHD", "QuestLogPanelOriginalHD")
ICON = re.compile(r"QuestIcons[\\/]a(\d+)q(\d+)$", re.IGNORECASE)
BUTTON_TYPE = "QuestLogButtonWidget"


def load_json(path: Path):
    return json.loads(path.read_text(encoding="utf-8-sig"))


def quest_buttons() -> dict[str, tuple[int, int]]:
    """Widget name -> (act, quest number), read from each button's icon."""
    found: dict[str, tuple[int, int]] = {}
    for panel in PANELS:
        path = INDEX_DIR / f"{panel}.json.index.json"
        if not path.exists():
            raise SystemExit(f"missing layout index: {path}")
        for widget in load_json(path)["widgets"]:
            if widget.get("type") != BUTTON_TYPE:
                continue
            name = widget.get("name")
            match = ICON.search(widget.get("filename") or "")
            if not name or not match:
                raise SystemExit(f"{panel}: quest button {name!r} has no act/quest icon")
            act, number = int(match.group(1)), int(match.group(2))
            if found.setdefault(name, (act, number)) != (act, number):
                raise SystemExit(f"{name} maps to two different quests across panels")
    return found


def quest_strings() -> tuple[dict[str, list[str]], dict[str, dict]]:
    """Title key -> its step keys in shipped order, plus every row by key."""
    rows = {row["Key"]: row for row in load_json(STRINGS)}
    steps: dict[str, list[str]] = {}
    for key in rows:  # dict preserves the file order, which is the game's order
        for prefix in ("qstsa", "qsta"):
            match = re.fullmatch(rf"{prefix}(\d)q(\d)(.+)", key)
            if not match:
                continue
            title = f"qstsa{match.group(1)}q{match.group(2)}"
            steps.setdefault(title, []).append(key)
            break
    return steps, rows


def comment(row: dict | None) -> str:
    if not row:
        return ""
    text = (row.get("esES") or row.get("enUS") or "").replace("\n", " / ").strip()
    return f" // {text}" if text else ""


def main() -> None:
    buttons = quest_buttons()
    steps, rows = quest_strings()

    ordered = sorted(buttons.items(), key=lambda item: (item[1][0], item[1][1]))
    lines: list[str] = []
    lines.append("// generated by tools/gen_quest_catalog.py from game-data -- do not edit")
    lines.append("//")
    lines.append("// Every quest-log button carries its own icon name, and that name encodes the")
    lines.append("// act and quest it stands for (Quest0 -> QuestIcons\\\\a1q1). That is where the")
    lines.append("// act/number pair below comes from -- never from the button's position. The")
    lines.append("// keys address the game's own string table and are resolved at runtime with")
    lines.append("// Localization::Text(key), so the text is always in the player's language.")
    lines.append("//")
    lines.append("// stepKeys are the quest's objective lines in the order the game ships them.")
    lines.append("// Some carry a printf placeholder (the live counter, e.g. \"Monsters left: %d\")")
    lines.append("// and some are blank in a given locale; callers must skip what resolves empty.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("#include <cstdint>")
    lines.append("")
    lines.append("namespace D2RAccess::Generated {")
    lines.append("")
    lines.append("struct Quest {")
    lines.append("\tconst char* widget;      // quest-log button name, e.g. \"Quest0\"")
    lines.append("\tuint8_t act;             // 1-5, from the button's icon")
    lines.append("\tuint8_t number;          // quest number inside that act, from the icon")
    lines.append("\tconst char* titleKey;    // string-table key of the quest name")
    lines.append("\tconst char* const* stepKeys;")
    lines.append("\tuint8_t stepCount;")
    lines.append("};")
    lines.append("")

    for widget, (act, number) in ordered:
        title = f"qstsa{act}q{number}"
        keys = steps.get(title, [])
        ident = f"Steps_{widget}"
        lines.append(f"inline constexpr const char* {ident}[] = {{")
        for key in keys:
            lines.append(f"\t\"{key}\",{comment(rows.get(key))}")
        if not keys:
            lines.append("\tnullptr, // the shipped data carries no objective lines for this quest")
        lines.append("};")
    lines.append("")

    lines.append("inline constexpr Quest Quests[] = {")
    for widget, (act, number) in ordered:
        title = f"qstsa{act}q{number}"
        keys = steps.get(title, [])
        count = len(keys)
        lines.append(
            f"\t{{ \"{widget}\", {act}, {number}, \"{title}\", Steps_{widget}, {count} }},"
            f"{comment(rows.get(title))}"
        )
    lines.append("};")
    lines.append("")
    lines.append("}")
    lines.append("")

    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUTPUT.relative_to(ROOT)}: {len(ordered)} quests")


if __name__ == "__main__":
    main()
