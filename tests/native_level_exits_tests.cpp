#include "native_level_exits.h"
#include "level_exit_layout.h"
#include "entity_layout.h"
#include "test_support.h"
#include <array>
#include <cstring>
#include <limits>

using namespace D2RAccess;
using namespace LevelExitLayout;
using namespace EntityLayout;
namespace {
template<size_t N> struct Memory {
	std::array<uint8_t, N> data{};
	uintptr_t Address() const { return reinterpret_cast<uintptr_t>(data.data()); }
	template<class T> void At(size_t offset, T value) { std::memcpy(data.data() + offset, &value, sizeof(value)); }
};
struct Fixture {
	Memory<0xC0> active, nearRoom, farRoom, destinationRoom;
	Memory<0x200> level, destinationLevel;
	Memory<0x30> preset, node;
	Memory<0x60> row;
	Fixture() {
		active.At(RoomExtended, nearRoom.Address());
		nearRoom.At(ExtendedLevel, level.Address()); farRoom.At(ExtendedLevel, level.Address());
		level.At<uint32_t>(LevelId, 9); level.At(LevelFirstRoom, nearRoom.Address());
		nearRoom.At(RoomNext, farRoom.Address());
		nearRoom.At<int>(RoomTileX, 100); nearRoom.At<int>(RoomTileY, 100);
		farRoom.At<int>(RoomTileX, 200); farRoom.At<int>(RoomTileY, 300);
		for (auto* room : {&nearRoom, &farRoom}) {
			room->At<int>(RoomTileWidth, 8); room->At<int>(RoomTileHeight, 8);
		}
		farRoom.At(RoomPresets, preset.Address()); farRoom.At(RoomWarpNodes, node.Address());
		preset.At<uint32_t>(PresetType, WarpType); preset.At<uint32_t>(PresetClass, 3);
		preset.At<int>(PresetX, 11); preset.At<int>(PresetY, 27);
		node.At(WarpNodeDestination, destinationRoom.Address()); node.At(WarpNodeRow, row.Address());
		node.At<int32_t>(WarpNodeActive, 1); row.At<uint32_t>(LvlWarpId, 3);
		destinationRoom.At(ExtendedLevel, destinationLevel.Address()); destinationLevel.At<uint32_t>(LevelId, 10);
	}
	bool Read(std::vector<NativeLevelExits::Exit>& exits) { return NativeLevelExits::Read(active.Address(), exits); }
};
}

int main() {
	Fixture f;
	std::vector<NativeLevelExits::Exit> exits;
	Check(f.Read(exits) && exits.size() == 1, "unloaded distant room contributes its stairs without active-room neighbors");
	Check(exits[0].destination == 10 && exits[0].warp == 3, "destination is matched through the room warp list");
	f.preset.At<uint32_t>(PresetClass, 3 | (WarpIdMask + 1));
	Check(f.Read(exits) && exits.size() == 1 && exits[0].warp == 3, "preset matching uses the same low-byte warp ID as the native unit reader");
	Check(exits[0].position.x == 1011 && exits[0].position.y == 1527, "tile origins convert to subtiles before adding preset coordinates");
	const auto identity = NativeLevelExits::Identity(exits[0].position);
	Check(identity != 0 && identity != NativeLevelExits::Identity({1011, 1528}), "coordinate identity distinguishes exits");
	Check(NativeLevelExits::Identity({0, 0}) != 0, "origin does not collide with the no-exit sentinel");
	Check(NativeLevelExits::Identity({-1, 0}) == 0 && NativeLevelExits::Identity({65536, 0}) == 0, "invalid world coordinates are rejected");
	Check(NativeLevelExits::Identity({std::numeric_limits<double>::quiet_NaN(), 0}) == 0, "nonfinite positions cannot form an identity");
	f.preset.At<uint32_t>(PresetType, MonsterType);
	Check(f.Read(exits) && exits.empty(), "monster presets are never announced as exits");
	f.preset.At<uint32_t>(PresetType, WarpType);
	f.preset.At<uint32_t>(PresetClass, 8);
	Check(f.Read(exits) && exits.empty(), "unmatched warp IDs do not invent a destination");
	f.preset.At<uint32_t>(PresetClass, 3);
	f.node.At<int32_t>(WarpNodeActive, 0);
	Check(f.Read(exits) && exits.empty(), "disabled transitions remain silent");
	f.node.At<int32_t>(WarpNodeActive, 1);
	f.row.At<uint32_t>(LvlWarpNoInteract, 1);
	Check(f.Read(exits) && exits.empty(), "noninteractive proxy tiles are skipped");
	f.row.At<uint32_t>(LvlWarpNoInteract, 0);
	f.destinationLevel.At<uint32_t>(LevelId, 9);
	Check(f.Read(exits) && exits.empty(), "same-level rooms are outside the requested exit scope");
	f.destinationLevel.At<uint32_t>(LevelId, 10);
	f.preset.At<int>(PresetX, -1);
	Check(f.Read(exits) && exits.empty(), "negative preset positions are rejected");
	f.preset.At<int>(PresetX, 4000);
	Check(f.Read(exits) && exits.empty(), "out-of-room preset positions are rejected");
	f.preset.At<int>(PresetX, 11);
	f.farRoom.At<uintptr_t>(RoomPresets, 0);
	Check(f.Read(exits) && exits.empty(), "absent presets stay unknown and are never generated by the reader");
	f.farRoom.At(RoomPresets, f.preset.Address());
	f.preset.At(PresetNext, f.preset.Address());
	Check(!f.Read(exits) && exits.empty(), "cyclic presets fail closed with no partial results");
	f.preset.At<uintptr_t>(PresetNext, 0);
	f.farRoom.At(RoomNext, f.nearRoom.Address());
	Check(!f.Read(exits) && exits.empty(), "cyclic logical rooms are bounded");
	f.farRoom.At<uintptr_t>(RoomNext, 0);
	f.farRoom.At(ExtendedLevel, f.destinationLevel.Address());
	Check(!f.Read(exits) && exits.empty(), "foreign level pointers cannot leak another map's exits");
	f.farRoom.At(ExtendedLevel, f.level.Address());
	f.nearRoom.At<int>(RoomTileWidth, std::numeric_limits<int>::max());
	Check(!f.Read(exits), "corrupt dimensions cannot overflow coordinate conversion");
	f.nearRoom.At<int>(RoomTileWidth, 8);
	Check(f.Read(exits) && exits.size() == 1, "fixture restores to the distant exit");
	Check(!NativeLevelExits::Read(0, exits) && exits.empty(), "missing player room clears previous exits");

	std::vector<NativeLevelExits::MonsterPreset> monsters;
	Check(NativeLevelExits::ReadMonsters(f.active.Address(), monsters) && monsters.empty(), "a warp preset is not a monster preset");
	Memory<0x30> npc;
	f.preset.At(PresetNext, npc.Address());
	npc.At<uint32_t>(PresetType, MonsterType); npc.At<uint32_t>(PresetClass, 155);
	npc.At<int>(PresetX, 4); npc.At<int>(PresetY, 39);
	Check(NativeLevelExits::ReadMonsters(f.active.Address(), monsters) && monsters.size() == 1
		&& monsters[0].monster == 155 && monsters[0].room == f.farRoom.Address(),
		"an unloaded room's monster preset keeps its MonStats row and its room");
	Check(monsters[0].position.x == 1004 && monsters[0].position.y == 1539, "monster presets use the same subtile conversion as exits");
	Check(f.Read(exits) && exits.size() == 1, "a monster preset beside a warp leaves the exit list unchanged");
	npc.At<int>(PresetY, 40);
	Check(NativeLevelExits::ReadMonsters(f.active.Address(), monsters) && monsters.empty(), "a monster preset outside its room is rejected");
	npc.At(PresetNext, f.preset.Address());
	Check(!NativeLevelExits::ReadMonsters(f.active.Address(), monsters) && monsters.empty(), "cyclic monster presets fail closed");
	Passed();
}
